// Writes the Android widget background and card drawables for every app theme.
// A RemoteViews call can swap a drawable but cannot tint one on older Android,
// so each theme gets its own pair (same shapes as the dark defaults).
// Run with: npm run widget-themes
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");

const root = path.join(__dirname, "..");
const drawables = path.join(
  root,
  "modules/termix-widgets/android/src/main/res/drawable",
);

function loadThemes() {
  const source = fs.readFileSync(
    path.join(root, "src/constants/theme.ts"),
    "utf8",
  );
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS },
  });
  const mod = { exports: {} };
  new Function("module", "exports", outputText)(mod, mod.exports);
  return mod.exports;
}

function hex(triplet) {
  return (
    "#" +
    triplet
      .split(" ")
      .map((n) => Number(n).toString(16).padStart(2, "0"))
      .join("")
  );
}

/** The file name part of a theme id: tokyo-night becomes tokyo_night. */
function resourceName(id) {
  return id.replace(/-/g, "_");
}

function background(vars) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by npm run widget-themes. Do not edit. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
  <solid android:color="${hex(vars.background)}" />
  <stroke android:width="1dp" android:color="${hex(vars.border)}" />
  <corners android:radius="@dimen/termix_widget_radius" />
</shape>
`;
}

function card(vars) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by npm run widget-themes. Do not edit. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
  <solid android:color="${hex(vars.card)}" />
  <stroke android:width="1dp" android:color="${hex(vars.border)}" />
</shape>
`;
}

/** File name to content for every theme. */
function render() {
  const { THEME_VARS } = loadThemes();
  const files = {};
  for (const [id, vars] of Object.entries(THEME_VARS)) {
    const name = resourceName(id);
    files[`termix_widget_background_${name}.xml`] = background(vars);
    files[`termix_widget_card_${name}.xml`] = card(vars);
  }
  return files;
}

module.exports = { render, resourceName, drawables };

if (require.main === module) {
  for (const [file, content] of Object.entries(render())) {
    fs.writeFileSync(path.join(drawables, file), content);
  }
  console.log("Widget theme drawables written");
}
